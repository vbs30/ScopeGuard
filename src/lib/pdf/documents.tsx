import { Document, Page, Text, View, StyleSheet } from "@react-pdf/renderer";
import type { ReactElement } from "react";
import type { DocumentProps } from "@react-pdf/renderer";

export type PdfData = {
  kind: "scope" | "change"; project: string; client: string; currency: string; version: number; publishedAt?: string | null;
  scope?: { summary: string; deliverables: string[]; exclusions: string[]; milestones: string[]; assumptions: string[]; revisions: number; timeline?: string; notes?: string; priceCents: number };
  change?: { title: string; description: string; reason?: string | null; extraPriceCents: number; extraDays: number; status: string; createdAt: string;
    decision?: { decision: string; decidedAt: string; comment?: string | null } | null };
};

const s = StyleSheet.create({
  page: { padding: 48, fontSize: 11, fontFamily: "Helvetica", color: "#171717", lineHeight: 1.4 },
  brand: { fontSize: 10, color: "#737373", marginBottom: 14 },
  h1: { fontSize: 22, fontFamily: "Helvetica-Bold", marginBottom: 4 },
  meta: { color: "#525252", marginBottom: 14 },
  h2: { fontSize: 12, fontFamily: "Helvetica-Bold", marginTop: 14, marginBottom: 4 },
  li: { marginLeft: 10, marginBottom: 2 },
  box: { borderWidth: 1, borderColor: "#d4d4d4", padding: 10, marginTop: 14 },
  foot: { position: "absolute", bottom: 24, left: 48, right: 48, fontSize: 8, color: "#737373" },
});
const utc = (d: string) => new Date(d).toUTCString();
const money = (c: number, cur: string) => `${(c / 100).toLocaleString()} ${cur}`;
const List = ({ title, items }: { title: string; items?: string[] }) => items?.length ? (
  <View><Text style={s.h2}>{title}</Text>{items.map((x, i) => <Text key={i} style={s.li}>• {x}</Text>)}</View>) : null;

export function buildPdf(d: PdfData): ReactElement<DocumentProps> {
  const sc = d.scope; const ch = d.change;
  return (
    <Document title={`${d.project} - ${d.kind === "scope" ? "Scope of work" : "Change request"}`}>
      <Page size="A4" style={s.page}>
        <Text style={s.brand}>ScopeGuard</Text>
        <Text style={s.h1}>{d.kind === "scope" ? "Scope of work" : `Change request: ${ch?.title}`}</Text>
        <Text style={s.meta}>Project: {d.project} · Client: {d.client} · Scope version {d.version}</Text>
        {sc && (<View>
          <Text>{sc.summary}</Text>
          <List title="Deliverables" items={sc.deliverables} /><List title="Not included" items={sc.exclusions} />
          <List title="Milestones" items={sc.milestones} /><List title="Assumptions" items={sc.assumptions} />
          <View style={s.box}>
            <Text>Agreed price: {money(sc.priceCents, d.currency)}</Text>
            <Text>Included revision rounds: {sc.revisions}{sc.timeline ? ` · Timeline: ${sc.timeline}` : ""}</Text>
            {d.publishedAt && <Text>Published: {utc(d.publishedAt)}</Text>}
          </View>
          {sc.notes ? <View><Text style={s.h2}>Notes</Text><Text>{sc.notes}</Text></View> : null}
        </View>)}
        {ch && (<View>
          <Text style={s.h2}>Additional work</Text><Text>{ch.description}</Text>
          {ch.reason ? <View><Text style={s.h2}>Reason</Text><Text>{ch.reason}</Text></View> : null}
          <View style={s.box}>
            <Text>Additional price: {money(ch.extraPriceCents, d.currency)}</Text>
            <Text>Additional time: {ch.extraDays} day(s)</Text>
            <Text>Created: {utc(ch.createdAt)}</Text>
            <Text>Status: {ch.status.toUpperCase()}</Text>
            {ch.decision && <Text>Client decision: {ch.decision.decision} on {utc(ch.decision.decidedAt)}</Text>}
            {ch.decision?.comment ? <Text>Client comment: {ch.decision.comment}</Text> : null}
          </View>
        </View>)}
        <Text style={s.foot} fixed render={({ pageNumber, totalPages }) =>
          `Record of agreement generated by ScopeGuard. Not a legally certified electronic signature. Page ${pageNumber} of ${totalPages}`} />
      </Page>
    </Document>
  );
}
